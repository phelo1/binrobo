#!/usr/bin/env python3
"""Builds ../RESULTS_H1.md from the JSON files in ../results. Every number in the Rev H report is in this file or in the
JSON it is built from. Run after tests_mech.py, statics.py, dock_mc.py, mission.py and bom_revH.py."""
import os, json, math
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, '..', 'results')
J = lambda n: json.load(open(os.path.join(RES, n + '.json')))
mech, stat, dock, mis, bom = J('mech'), J('statics'), J('dock_mc'), J('mission'), J('bom_revH')
L = []; w = L.append


def table(head, rows):
    w('| ' + ' | '.join(head) + ' |'); w('|' + '|'.join(['---'] * len(head)) + '|')
    for r in rows: w('| ' + ' | '.join(str(c) for c in r) + ' |')
    w('')


def tally(rows):
    return '%d of %d' % (sum(1 for r in rows if r['ok']), len(rows))


ob = mech['obstacles']; wl = mech['wet_leaves_steps']; gr = mech['grades']; meta = mech['meta']
R = meta['ROBOT']; rm = meta['robot']
w('# Bin Tug Rev H: results H1'); w('')
w('Generated by `sim/make_results_md.py` on %s from the JSON files in `results/`. Nothing here has been built or bench-tested.' % meta['date'])
w('Models are first-order (see `sim/dyn.py`): a rigid body with x, z, pitch and roll, penalty wheel contact, stick-slip tyre friction. No yaw, no MuJoCo, no ArduPilot.'); w('')

w('## 1. Robot'); w('')
full = next(r for r in mech['loads'] if r['bin'].startswith('ESE 240 SL') and r['fill'] == 1.0)
unl = mech['loads'][0]
table(['Item', 'Value'], [
    ['Length x width x height', '%.2f x %.2f x %.2f m' % (R['nose_tip_x'] - R['leg_tip_x'], R['width'], R['height'])],
    ['Drive track / wheel radius', '%.2f m / %.3f m' % (R['drive_track'], R['drive_r'])],
    ['Nose casters', 'radius %.3f m at x = %.2f m' % (R['nose_r'], R['nose_x'])],
    ['Anti-tip wheels', 'x = %.2f m, track %.2f m, %.0f mm off the ground' % (R['tail_x'], R['tail_track'], R['tail_gap'] * 1000)],
    ['Clear width between rails / funnel mouth', '%.2f m / %.2f m' % (R['leg_inner_gap'], R['funnel_mouth'])],
    ['Comb travel', '%.2f to %.2f m; lift %.0f mm' % (R['comb_z_min'], R['comb_z_max'], R['lift'] * 1000)],
    ['Robot mass, CG', '%.1f kg, x %.3f m, z %.3f m' % (unl['mass_kg'], unl['cg_x'], unl['cg_z'])],
    ['With a full 240 L bin', '%.1f kg, CG x %.3f m, z %.3f m; %.1f kg on the drive wheels, %.1f kg on the nose casters' % (full['mass_kg'], full['cg_x'], full['cg_z'], full['drive_kg'], full['nose_kg'])]])

w('## 2. Layout study (why the first sketch was dropped)'); w('')
table(['Layout', 'Unladen nose share %', 'Step cases passed'], [[v['variant'], v['unladen_nose_pct'], '%d of %d' % (v['passes'], v['of'])] for v in mech['layout']])

w('## 3. Obstacles'); w('')
w('Loads: unladen, empty 240 L, full 240 L (110 kg), full 140 L (70 kg). Torque limit 60 N m per wheel unless stated.'); w('')
w('### 3.1 Square step up, full width'); w('')
rows = []
for mu in (0.6, 0.45, 0.3):
    src = wl if mu == 0.3 else ob
    for h in sorted(set(r['h_mm'] for r in src if r['kind'] == 'step' and r['h_mm'] > 0 and not r['onesided'] and r['mu'] == mu and r['t_lim'] == 60.0)):
        for v in (0.5, 0.8):
            rr = [r for r in src if r['kind'] == 'step' and not r['onesided'] and r['mu'] == mu and r['h_mm'] == h and r['v'] == v and r['t_lim'] == 60.0]
            if rr: rows.append([mu, h, v, tally(rr), ', '.join(r['load'] for r in rr if not r['ok']) or '-'])
table(['Friction', 'Step mm', 'Speed m/s', 'Pass', 'Loads that stall'], rows)
hi = [r for r in ob if r['kind'] == 'step' and r['h_mm'] > 0 and r['t_lim'] != 60.0]
if hi:
    w('With the torque limit raised to %.0f N m (full 240 L): ' % hi[0]['t_lim'] + '; '.join('%d mm at %.1f m/s %s' % (r['h_mm'], r['v'], 'pass' if r['ok'] else 'stall') for r in hi) + '.'); w('')
w('### 3.2 Other obstacles'); w('')
def kind_of(r):
    return r['kind'] if r['kind'] != 'step' else ('step up' if r['h_mm'] > 0 else 'step down')


oth = [r for r in ob if kind_of(r) != 'step up']
rows = []
for kind, one in sorted(set((kind_of(r), r['onesided']) for r in oth)):
    for h in sorted(set(abs(r['h_mm']) for r in oth if kind_of(r) == kind and r['onesided'] == one)):
        for v in sorted(set(r['v'] for r in oth)):
            rr = [r for r in oth if kind_of(r) == kind and r['onesided'] == one and abs(r['h_mm']) == h and r['v'] == v]
            if not rr: continue
            fullr = [r['comb_load_factor'] for r in rr if r['load'].startswith('full') and r['comb_load_factor'] is not None]
            rows.append([{'pothole': 'trench' if not one else 'pothole'}.get(kind, kind), 'one side' if one else 'full width', h, v, tally(rr), max(fullr) if fullr else '-'])
table(['Obstacle', 'Where', 'Size mm', 'Speed m/s', 'Pass', 'Peak lip load factor, full bins'], rows)
gaps = [r['lip_gap_mm'] for r in ob + wl if r.get('lip_gap_mm') is not None]
stepf = [r['comb_load_factor'] for r in ob + wl if r['kind'] == 'step' and r['h_mm'] > 0 and r['load'].startswith('full') and r['comb_load_factor'] is not None]
w('Largest gap between lip and comb in any obstacle run: %.1f mm. Peak lip load factor on step-up runs with full bins: %.1f. '
  'The lip load factor is the peak comb force divided by the bin\'s weight, from a rigid-tyre model, so it is likely pessimistic; a real tyre and a rubber buffer under the comb soften it.' % (max(gaps), max(stepf))); w('')
w('### 3.3 Hand check of the step results'); w('')
mod = {(r['load'], r['mu'], r['h_mm'], r['v']): r['ok'] for r in ob + wl if r['kind'] == 'step' and not r['onesided'] and r['t_lim'] == 60.0}
se = [r for r in stat['step_energy']['rows'] if (r['load'], r['mu'], r['h_mm'], r['v']) in mod]
dis = [r for r in se if r['passes'] != mod[(r['load'], r['mu'], r['h_mm'], r['v'])]]
w('`statics.step_energy()` is an energy balance on the drive wheel climbing the step corner, with no code shared with the dynamic model. '
  'It agrees with the model in %d of %d runs. The %d disagreements:' % (len(se) - len(dis), len(se), len(dis))); w('')
table(['Load', 'Friction', 'Step mm', 'Speed m/s', 'Energy short J', 'Kinetic energy after impact J', 'Hand check', 'Model'],
      [[r['load'], r['mu'], r['h_mm'], r['v'], r['energy_short_J'], r['kinetic_after_impact_J'], 'pass' if r['passes'] else 'stall',
        'pass' if mod[(r['load'], r['mu'], r['h_mm'], r['v'])] else 'stall'] for r in dis])
w('### 3.4 Rev G in the same model (calibration)'); w('')
table(['Bump mm', 'One side', 'This model', 'Project MuJoCo'], [[r['h_mm'], r['onesided'], 'pass' if r['ok'] else 'stall', r.get('mujoco_published', '-')] for r in mech['revg_ref']['bumps']])
w('The model does not reproduce Rev G\'s MuJoCo stalls at 50 and 60 mm: it has no yaw, and Rev G\'s stall is a jack-knife. Rev H is therefore rated on full-width steps, not on these.'); w('')

w('## 4. Grades'); w('')
rows = []
for mode in sorted(set(r['mode'] for r in gr)):
    rr = [r for r in gr if r['mode'] == mode]
    rows.append([mode, tally(rr), ', '.join(sorted(set('%s %s%% mu %s' % (r['load'], r['grade_pct'], r['mu']) for r in rr if not r['ok']))) or '-'])
table(['Case', 'Pass', 'Failures'], rows)
st = [r for r in gr if r.get('stop_dist_m') is not None and isinstance(r.get('stop_dist_m'), float) and not math.isnan(r['stop_dist_m'])]
if st:
    table(['E-stop case', 'Load', 'Grade %', 'Friction', 'Speed at brake m/s', 'Stop distance m'],
          [[r['mode'], r['load'], r['grade_pct'], r['mu'], r.get('v_at_brake', ''), r['stop_dist_m']] for r in st if r['load'].startswith('full') and r['grade_pct'] == 12.0])
holds = [r for r in gr if r['mode'].startswith('hold')]
if holds:
    table(['Hold case', 'Load', 'Grade %', 'Friction', 'Creep m', 'Holds'], [[r['mode'], r['load'], r['grade_pct'], r['mu'], r.get('creep_m', ''), r['ok']] for r in holds])
cl = [r for r in gr if r['mode'] == 'climb' and r['grade_pct'] == 12.0 and r['mu'] == 0.3]
table(['12 % climb, friction 0.3', 'Speed cmd m/s', 'Least nose-caster load N', 'Anti-tip wheel load N'], [[r['load'], r['v_cmd'], r['nose_min_N'], r['tail_max_N']] for r in cl])

w('## 5. Statics'); w('')
lf = stat['lift']
table(['Bin', 'Gross kg', 'Comb mm', 'Mast moment N m', 'Lift force, rollers N', 'Actuator margin (3 kN)'],
      [[r['bin'], r['gross_kg'], r['comb_mm'], r['mast_moment_Nm'], r['lift_force_rollers_N'], r['actuator_margin_rollers']] for r in lf['per_bin']])
table(['Member', 'Static stress MPa', 'Stress at 3 g MPa', 'Safety factor at 3 g (S235)'],
      [[k, v.get('stress_static_MPa', v.get('bearing_static_MPa')), v.get('stress_3g_MPa', v.get('bearing_3g_MPa')), v.get('sf_3g_S235', 'HDPE yield ' + str(v.get('hdpe_yield_MPa')))] for k, v in stat['structure'].items()])
table(['Load', 'Mass kg', 'Sideways tip angle deg', 'Margin on a 30 % cross-slope', 'Tip-back grade %', 'Nose share on a 12 % climb %'],
      [[r['load'], r['mass_kg'], r['lateral_tip_deg'], r['cross_slope_30pct_margin'], r['tip_back_grade_pct'], r['nose_share_12pct_climb_pct']] for r in stat['stability']['rows']])
w('Acceleration needed to swing a hanging full bin off the rest pad: %.2f g. ' % stat['stability']['bin_swing_out']['accel_g'] +
  'Torque limit 60 N m per wheel is about %.0f A at the motor, 80 N m about %.0f A (assumed motor constant).' % (stat['drive']['t_lim_60Nm_equals_A'], stat['drive']['t_lim_80Nm_equals_A'])); w('')

w('## 6. Docking tolerance model'); w('')
w('%d draws per bin and case. %s' % (dock['n_per_bin'], dock['note'])); w('')
table(['Case', 'First try %', 'With one re-approach %'], [[k, v['mean_first_try_pct'], v['mean_with_retry_pct']] for k, v in dock['cases'].items()])
table(['Bin', 'Side clearance at the wheels mm', 'Funnel capture mm', 'Comb height mm', 'Lift reserve mm'],
      [[e['bin'], e['lateral_at_wheels_mm'], e['mouth_capture_mm'], e['comb_mm'], e['lift_reserve_mm']] for e in dock['envelope']])

w('## 7. Evenings on the lane profile (%.0f m)' % mis['lane_m']); w('')
table(['Cruise m/s', 'Bins', 'Kind', 'Minutes', 'Wh', 'Within the %s Wh plan' % mis['evenings'][0]['battery_plan_wh'], 'Finish if started 18:00'],
      [[e['v_cruise'], e['bins'], e['kind'], e['minutes'], e['wh'], e['within_plan'], e['finish_clock_if_start_1800']] for e in mis['evenings']])
g = mis['revg_sitl']
w('Rev G SITL for comparison: one-bin drop %.1f min and %.1f Wh; three-bin drop %.0f min and %.0f Wh (G4); three-bin pickup %.0f min (G3).' %
  (g['one_bin_drop_min'], g['one_bin_drop_wh'], g['three_bin_drop_G4_min'], g['three_bin_drop_G4_wh'], g['three_bin_pickup_G3_min'])); w('')
table(['Placement case', 'p50 mm', 'p95 mm', 'Yaw p95 deg', 'Over 0.6 m %'], [[k, v['p50_mm'], v['p95_mm'], v['yaw_p95_deg'], v['over_0p6m_pct']] for k, v in mis['placement']['cases'].items()])
table(['Turning case', 'Width for a 180 degree turn m', 'Fits a 3.6 m lane'], [[k, v['u_turn_width_m'], v['fits_3p6m_lane']] for k, v in mis['turning'].items()])

w('## 8. Cost'); w('')
s = bom['summary']; h = s['rev_h']; gp = s['rev_g_published']; gc = s['rev_g_completed_all_in']
table(['', 'Parts EUR', 'All-in EUR'], [
    ['Rev G as published', gp['parts'], gp['all_in']],
    ['Rev G finished (low / mid / high)', '%.0f / %.0f / %.0f' % tuple(gp['parts'] + s['rev_g_owed_totals'][k] for k in ('low', 'mid', 'high')), '%.0f / %.0f / %.0f' % (gc['low'], gc['mid'], gc['high'])],
    ['Rev H', h['parts'], h['all_in']],
    ['Rev H with the conditional savings (EUR %s)' % s['rev_h_conditional_total'], round(h['parts'] - s['rev_h_conditional_total'], 2), s['rev_h_lean_all_in']]])
w('Rev H all-in = parts %.2f + logistics %.2f + contingency %.2f. %d lines; %d carried from Rev G unchanged.' %
  (h['parts'], h['logistics'], h['contingency'], h['lines'], sum(1 for l in bom['lines'] if l['status'].startswith('G4')))); w('')
table(['Area', 'Rev H EUR', 'Rev G EUR'], [[k, v, gp['by_area'].get(k, '-')] for k, v in s['rev_h_by_area'].items()] + [[k, '-', v] for k, v in gp['by_area'].items() if k not in s['rev_h_by_area']])
table(['Function', 'Parts EUR'], [[k, v] for k, v in s['rev_h_by_function'].items()])
table(['Stage', 'Parts EUR', 'Cumulative EUR'], [[k, v['parts'], v['cumulative_parts']] for k, v in s['stages'].items()])
table(['Item Rev G still owes', 'Low', 'Mid', 'High', 'Called for in'], s['rev_g_owed'])
table(['Conditional saving', 'EUR', 'Condition'], s['rev_h_conditional'])
w('The full parts list is `results/bom_revH.csv`. Price status follows the project convention: G4-checked, est, excerpt.'); w('')

w('## 9. What these results do not show'); w('')
for t in ['Contact between comb and lip, or between rails and bin: the docking figures are a tolerance stack.',
          'Yaw: one-sided obstacle results are optimistic.',
          'Software: no SITL run was made. Timings come from a kinematic model of the lane profile, checked against one Rev G SITL run.',
          'The real bins: EN 840 comb dimensions came from a text extract of the 2004 edition; seven bins use maker data sheets.',
          'Prices: most new lines are estimates or search excerpts dated 11 November 2026.']:
    w('- ' + t)
open(os.path.join(HERE, '..', 'RESULTS_H1.md'), 'w').write('\n'.join(L) + '\n')
print('wrote RESULTS_H1.md,', len(L), 'lines')
